"""Aggregate scored M4 records into results/RESULTS.md with the frozen pass logic (PHASE_1_M4_PREREGISTRATION.md
section 5, Option A: every criterion in 100 % of scored trials of E1-1 ... E1-6, including E1-5s and E1-6m).
Every record is included; nothing is filtered. The no-magnet arm (E1-6n, results_nomag/) is reported only.
E1-8 (throughput) is a separate bench script and is not aggregated here."""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
OUT, OUT_NOMAG = HERE / "results", HERE / "results_nomag"
EXPECTED = {"E1-1": 20, "E1-2": 24, "E1-3": 22, "E1-4": 40, "E1-5": 42, "E1-5s": 20, "E1-6a": 6, "E1-6b": 6,
            "E1-6c": 8}
ROWS = ["E1-1", "E1-2", "E1-3", "E1-4", "E1-5", "E1-5s", "E1-6a", "E1-6b", "E1-6c"]


def load(root: Path) -> dict:
    by = defaultdict(list)
    for f in sorted(root.glob("E1-*/*.json")):
        r = json.loads(f.read_text())
        by[r["sub_experiment"]].append(r)
    return by


def _mx(recs, key, sub=None):
    vals = []
    for r in recs:
        if sub:
            vals += [abs(m[key]) for m in r.get(sub, []) if m.get(key) is not None]
        elif r.get(key) is not None:
            vals.append(abs(r[key]))
    return max(vals) if vals else None


def _fmt(x, f="{:.3g}"):
    return "–" if x is None else f.format(x)


def e16m_moves(by: dict) -> list[dict]:
    return [m for e in ("E1-2", "E1-3", "E1-4") for r in by.get(e, []) for m in r.get("per_move", [])]


def report(root: Path = OUT, root_nomag: Path = OUT_NOMAG) -> str:
    by, nm = load(root), load(root_nomag)
    commits = {r["source_commit"] for rs in by.values() for r in rs}
    tilts = {r.get("validated_tilt_deg") for rs in by.values() for r in rs}
    L = ["# G1 scored results — M4 (auto-generated by analyze.py)", "",
         f"Source commit(s): {', '.join(sorted(commits)) or 'none'}; validated near-pair tilt: "
         f"{', '.join(str(t) for t in sorted(tilts, key=str)) or '–'} deg", "",
         "| Experiment | Trials run / pre-registered | Passed | Max near-pair tilt (deg) | Verdict |",
         "|---|---|---|---|---|"]
    verdict = True
    for e in ROWS:
        rs = by.get(e, [])
        n_pass = sum(r["pass"] for r in rs)
        complete = len(rs) == EXPECTED[e]
        ok = complete and n_pass == len(rs)
        verdict &= ok
        tilt = max((r["magnet_stats"]["max_near_tilt_deg"] for r in rs if r.get("magnet_stats")), default=None)
        L.append(f"| {e} | {len(rs)} / {EXPECTED[e]} | {n_pass} | {_fmt(tilt, '{:.2f}')} | "
                 f"{'PASS' if ok else ('INCOMPLETE' if not complete else 'FAIL')} |")
    mv = e16m_moves(by)
    p_ok = [m.get("e16m_P_ok") for m in mv]
    seq_complete = all(len(by.get(e, [])) == EXPECTED[e] for e in ("E1-2", "E1-3", "E1-4"))
    e16m_ok = seq_complete and bool(p_ok) and all(x is True for x in p_ok)
    verdict &= e16m_ok
    L.append(f"| E1-6m ⟨P⟩ (per move, E1-2…E1-4) | {len(p_ok)} moves | {sum(x is True for x in p_ok)} | | "
             f"{'PASS' if e16m_ok else ('INCOMPLETE' if not seq_complete else 'FAIL')} |")
    L += ["", f"**G1 quantitative/categorical verdict for M4 (Option A): {'PASS' if verdict else 'NOT PASSED'}** "
          "(E1-7 and E1-8 must also be published; the E1-6c criterion follows section 8 decision 1; G1 needs user "
          "sign-off).", ""]

    seq = by.get("E1-2", []) + by.get("E1-3", []) + by.get("E1-4", [])
    L += ["## Worst observed values in move trials (E1-2…E1-4)", "",
          f"* turn error: {_mx(seq, 'turn_error_deg', 'per_move')} deg (limit 2)",
          f"* non-target drift: {_mx(seq, 'nontarget_drift_deg', 'per_move')} deg (limit 1)",
          f"* penetration: {_mx(seq, 'penetration_mm', 'per_move')} mm (limit 0.5)",
          f"* radial position above nominal: {_mx(seq, 'radial_above_nominal_mm_so_far', 'per_move')} mm (limit 0.3)",
          f"* turner torque: {_mx(seq, 'max_turner_torque_Nm', 'per_move')} N m (reported)",
          f"* per-piece misalignment after a move (D8-0, worst piece): "
          f"{_fmt(max((m['misalignment']['max_err_deg'] for r in seq for m in r.get('per_move', []) if m.get('misalignment')), default=None))} deg (reported)", ""]

    L += ["## E1-4 misalignment growth (criterion for 40-move runs: slope < 0.005 deg/move)", "",
          "| trial | moves ok | slope (deg/move) | criterion | pass |", "|---|---|---|---|---|"]
    for r in sorted(by.get("E1-4", []), key=lambda r: r["trial_id"]):
        L.append(f"| {r['trial_id']} | {r.get('moves_completed_ok')}/{len(r['sequence'].split())} | "
                 f"{_fmt(r.get('misalignment_growth_slope_deg_per_move'), '{:+.4f}')} | "
                 f"{'yes' if r.get('growth_slope_is_criterion') else 'reported'} | {r['pass']} |")

    L += ["", "## E1-5s snap-back (criterion for |delta| >= 3 deg: |U error after 1 s| <= 0.5 deg)", "",
          "| delta (deg) | seed | U error after release | after 1 s | criterion | pass |", "|---|---|---|---|---|---|"]
    for r in sorted(by.get("E1-5s", []), key=lambda r: (r["spec"]["delta_deg"], r["spec"]["seed"])):
        L.append(f"| {r['spec']['delta_deg']:+.0f} | {r['spec']['seed']} | "
                 f"{_fmt(r.get('U_err_after_release_deg'), '{:+.3f}')} | {_fmt(r.get('U_err_after_1s_deg'), '{:+.3f}')} | "
                 f"{'yes' if r.get('snap_is_criterion') else 'reported'} | {r['pass']} |")

    e5 = sorted(by.get("E1-5", []), key=lambda r: r["spec"]["misalign_deg"])
    L += ["", "## E1-5 forgiveness (categorical; boundary reported)", "",
          "| commanded U (deg) | measured U (deg) | R rotation (deg) | outcome | pass |", "|---|---|---|---|---|"]
    for r in e5:
        L.append(f"| {r['spec']['misalign_deg']:+.0f} | {r.get('U_misalignment_deg', float('nan')):+.2f} | "
                 f"{r.get('R_rotation_deg', float('nan')):+.2f} | {r.get('outcome', r.get('aborted'))} | {r['pass']} |")

    L += ["", "## E1-6m magnet energy and impulse per move", ""]
    if mv:
        res = np.array([abs(m["e16m_residual_J"]) for m in mv if m.get("e16m_residual_J") is not None])
        bnd = np.array([m["e16m_bound_J"] for m in mv if m.get("e16m_residual_J") is not None])
        L += [f"* moves: {len(mv)}; ⟨P⟩ holds in {sum(x is True for x in p_ok)}",
              f"* |W_mag + dU_mag|: max {_fmt(res.max() * 1e3 if len(res) else None)} mJ; worst ratio to bound "
              f"{_fmt((res / bnd).max() if len(res) else None)}",
              f"* |dU_mag| max {_fmt(_mx([{'pm': mv}], 'magnet_dU_J', 'pm'))} J; U range max "
              f"{_fmt(_mx([{'pm': mv}], 'magnet_U_range_J', 'pm'))} J",
              f"* peak magnet force on the turning layer {_fmt(_mx([{'pm': mv}], 'layer_magnet_force_peak_N', 'pm'))} N; "
              f"peak axial torque {_fmt(_mx([{'pm': mv}], 'layer_magnet_axis_torque_peak_Nm', 'pm'))} N m; "
              f"impulse max {_fmt(_mx([{'pm': mv}], 'layer_magnet_impulse_Ns', 'pm'))} N s",
              f"* one callback call per step in every move: "
              f"{all(m.get('magnet_buf_one_call_per_step') for m in mv)}"]
    else:
        L.append("* no move records")

    L += ["", "## E1-6 negative controls (rule 3 labels for E1-6b/c)", "",
          "| trial | pass | max tilt (deg) | rule 3 label | key values |", "|---|---|---|---|---|"]
    for e in ("E1-6a", "E1-6b", "E1-6c"):
        for r in by.get(e, []):
            keys = ["layer_rotation_deg", "layer_rotations_deg", "observed_valid", "radial_change_mm",
                    "penetration_mm_reported_only", "max_twist_deg", "torque_at_twist_15deg_Nm",
                    "final_observed_valid", "final_solved", "aborted"]
            kv = "; ".join(f"{k}={r[k]}" for k in keys if k in r)
            tilt = (r.get("magnet_stats") or {}).get("max_near_tilt_deg")
            L.append(f"| {r['trial_id']} | {r['pass']} | {_fmt(tilt, '{:.2f}')} | {r.get('rule3_label') or ''} | {kv} |")

    L += ["", "## Failed trials (reasons)", ""]
    for e in ROWS:
        for r in by.get(e, []):
            if r["pass"]:
                continue
            bad = [k for k, v in r.items() if k.startswith("ok_") and v is False]
            for m in r.get("per_move", []):
                bad += [f"{m['move']}:{k}" for k, v in m.items() if k.startswith("ok_") and k != "ok_all" and not v]
            L.append(f"* {e}/{r['trial_id']}: {'; '.join(r.get('fail_reasons', []))} [{', '.join(bad)}]"
                     f"{' ' + r['aborted'] if r.get('aborted') else ''}")

    L += ["", "## E1-6n no-magnet arm (reported only, no threshold)", "",
          "| experiment | trials (no magnets) | pass without magnets | pass with magnets (same ids) |", "|---|---|---|---|"]
    for e in ROWS:
        rs = nm.get(e, [])
        if e == "E1-1":
            continue
        with_mag = {r["trial_id"]: r["pass"] for r in by.get(e, [])}
        L.append(f"| {e} | {len(rs)} | {sum(r['pass'] for r in rs)} | "
                 f"{sum(with_mag.get(r['trial_id'], False) for r in rs)} |")
    snap_nm = sorted(nm.get("E1-5s", []), key=lambda r: (r["spec"]["delta_deg"], r["spec"]["seed"]))
    if snap_nm:
        L += ["", "E1-5s without magnets: " + ", ".join(
            f"{r['spec']['delta_deg']:+.0f}: {_fmt(r.get('U_err_after_1s_deg'), '{:+.2f}')}" for r in snap_nm)]

    e7 = by.get("E1-7", [])
    L += ["", "## E1-7 sensitivity (outcome per setting; flips are fragilities). Radial preload dropped (B1).", "",
          "| setting | 6-move | sexy6 | max tilt (deg) |", "|---|---|---|---|"]
    settings = defaultdict(dict)
    for r in e7:
        tag, sname = r["trial_id"].split("__")
        settings[tag][sname] = "pass" if r["pass"] else "FAIL"
        t = (r.get("magnet_stats") or {}).get("max_near_tilt_deg")
        settings[tag]["tilt"] = max(settings[tag].get("tilt") or 0.0, t) if t is not None else settings[tag].get("tilt")
    for tag in sorted(settings):
        s = settings[tag]
        L.append(f"| {tag} | {s.get('6move', '-')} | {s.get('sexy6', '-')} | {_fmt(s.get('tilt'), '{:.2f}')} |")
    L += ["", "E1-8 (throughput, with and without magnets, 1/4/8/16 processes) is a separate bench script.", ""]
    return "\n".join(L) + "\n"


def main() -> None:
    text = report()
    if "--print" not in sys.argv:
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / "RESULTS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
