"""ER2 part O2 analysis (PROTOCOL.md; D11's slip definition). Reads results/rest_*.json.gz; prints a markdown report."""
from __future__ import annotations

import gzip
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
spec = importlib.util.spec_from_file_location("d11_analyze", REPO / "experiments/D11_rest_slip_count/d11_analyze.py")
D11 = importlib.util.module_from_spec(spec); sys.modules["d11_analyze"] = D11; spec.loader.exec_module(D11)


def main() -> None:
    data: dict[str, dict[int, dict]] = {}
    for p in sorted((HERE / "results").glob("rest_G*_s*.json.gz")):
        r = json.loads(gzip.decompress(p.read_bytes()))
        rec = r["record"]; ts = rec["timeseries"]
        t = np.array(ts["t"]) - ts["t"][0] + D11.DT
        ev = D11.events(rec, t)
        data.setdefault(r["arm"], {})[r["seed"]] = {"peak": r["rest_rotation_deg"], "ev": ev,
                                                    "pen": rec["penetration_mm"], "aborted": rec.get("aborted"),
                                                    "cubie": r["attribution"]["peak_cubie"],
                                                    "tilt": (rec.get("magnet_stats") or {}).get("max_near_tilt_deg")}
    lines = ["# ER2 O2 report (generated by er2_rest_analyze.py)", "",
             "| arm | seeds | slips 0–10 s (seeds) | slips 0–60 s (seeds) | events | event size min / median / max ° | "
             "0–10 s peak median / max ° | seeds > 0.5° | max penetration mm | max magnet tilt ° | aborted |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ("G050", "G025"):
        d = data.get(arm, {})
        n = len(d)
        s10 = sum(any(e["t_start_s"] <= 10 for e in v["ev"]) for v in d.values())
        s60 = sum(bool(v["ev"]) for v in d.values())
        sizes = [e["size_deg"] for v in d.values() for e in v["ev"]]
        peaks = [v["peak"] for v in d.values()]
        lo10, hi10 = D11.cp(s10, n); lo60, hi60 = D11.cp(s60, n)
        sz = f"{min(sizes):.3f} / {np.median(sizes):.3f} / {max(sizes):.3f}" if sizes else "–"
        lines.append(f"| {arm} | {n} | {s10} ({lo10:.2f}–{hi10:.2f}) | {s60} ({lo60:.2f}–{hi60:.2f}) | {len(sizes)} | {sz} | "
                     f"{np.median(peaks):.3f} / {max(peaks):.3f} | {sum(p > 0.5 for p in peaks)} | "
                     f"{max(v['pen'] for v in d.values()):.3f} | {max((v['tilt'] or 0) for v in d.values()):.2f} | "
                     f"{sum(bool(v['aborted']) for v in d.values())} |")
    lines += ["", "## Per seed", "", "| seed | G050 peak ° | G050 slips | G025 peak ° | G025 slips | G025 − G050 ° |",
              "|---|---|---|---|---|---|"]
    diffs = []
    for s in sorted(set(data.get("G050", {})) | set(data.get("G025", {}))):
        a, b = data["G050"].get(s), data["G025"].get(s)
        fmt = lambda v: "; ".join(f"{e['t_start_s']:.2f}s {e['cubie'][6:]} {e['size_deg']:.2f}°" for e in v["ev"]) or "–"  # noqa: E731
        dd = b["peak"] - a["peak"] if a and b else float("nan")
        diffs.append(dd)
        lines.append(f"| {s} | {a['peak']:.4f} | {fmt(a)} | {b['peak']:.4f} | {fmt(b)} | {dd:+.4f} |")
    dd = np.array([x for x in diffs if np.isfinite(x)])
    lines += ["", f"Paired difference G025 − G050 (0–10 s peak): median {np.median(dd):+.4f}°, "
                  f"G025 lower in {int((dd < 0).sum())} / {len(dd)} seeds."]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
