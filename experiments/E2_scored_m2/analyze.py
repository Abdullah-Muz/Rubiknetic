"""Aggregate scored M2 records into results/RESULTS.md using the frozen pass logic
(Option A: every criterion in 100 % of scored trials of E1-1 to E1-6, plus E1-5 switch transitions).
Every record is included; nothing is filtered."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).parent / "results"
EXPECTED = {"E1-1": 20, "E1-2": 24, "E1-3": 22, "E1-4": 40, "E1-5b": 42, "E1-6": 26}


def main() -> None:
    by = defaultdict(list)
    for f in sorted(OUT.glob("E1-*/*.json")):
        r = json.loads(f.read_text())
        by[r["experiment"]].append(r)
    commits = {r["source_commit"] for rs in by.values() for r in rs}
    lines = ["# G1 scored results — M2 (auto-generated by analyze.py)", "",
             f"Source commit(s): {', '.join(sorted(commits)) or 'none'}", "",
             "| Experiment | Trials run / pre-registered | Passed | Verdict |", "|---|---|---|---|"]
    verdict = True
    for exp in ["E1-1", "E1-2", "E1-3", "E1-4", "E1-5b", "E1-6"]:
        rs = by.get(exp, [])
        n_pass = sum(r["pass"] for r in rs)
        complete = len(rs) == EXPECTED[exp]
        ok = complete and n_pass == len(rs)
        verdict &= ok
        lines.append(f"| {exp} | {len(rs)} / {EXPECTED[exp]} | {n_pass} | "
                     f"{'PASS' if ok else ('INCOMPLETE' if not complete else 'FAIL')} |")
    # E1-5 switch transitions over E1-2..E1-4
    checks = [c for e in ("E1-2", "E1-3", "E1-4") for r in by.get(e, []) for c in r.get("e1_5", {}).get("checks", [])]
    n_fail = sum(not c["ok"] for c in checks)
    e15_ok = bool(checks) and n_fail == 0
    verdict &= e15_ok
    lines.append(f"| E1-5 switch transitions (E1-2..E1-4) | {len(checks)} switches | {len(checks) - n_fail} | "
                 f"{'PASS' if e15_ok else ('NO DATA' if not checks else 'FAIL')} |")
    lines += ["", f"**G1 quantitative/categorical verdict for M2 (Option A): {'PASS' if verdict else 'NOT PASSED'}** "
              "(E1-7 and E1-8 must also be published; G1 needs user sign-off).", ""]
    if checks:
        done = [c for c in checks if c.get("complete")]
        lines += ["## E1-5 switch statistics", "",
                  f"* max |dKE| {max((c['abs_dke_J'] for c in done), default=0):.3g} J; "
                  f"max post-activation pose error {max((c['pos_err_post_mm'] for c in done), default=0):.4f} mm; "
                  f"incomplete measurements {sum(not c.get('complete') for c in checks)}", ""]
    seq = by.get("E1-2", []) + by.get("E1-3", []) + by.get("E1-4", [])
    mx = lambda k: max((abs(m[k]) for r in seq for m in r.get("per_move", []) if m.get(k) is not None), default=None)  # noqa: E731
    lines += ["## Worst observed values in move trials (E1-2…E1-4)", "",
              f"* turn error (unwrapped): {mx('turn_error_deg')} deg (limit 2)",
              f"* non-target drift: {mx('nontarget_drift_deg')} deg (limit 1)",
              f"* penetration: {mx('penetration_mm')} mm (limit 0.5)",
              f"* radial above nominal: {mx('radial_above_nominal_mm_so_far')} mm (limit 0.3)",
              f"* turner torque: {mx('max_turner_torque_Nm')} N m (reported)", ""]
    lines += ["## E1-5b misaligned perpendicular turn (categorical)", "",
              "| commanded U (deg) | measured U (deg) | R rotation (deg) | outcome | pass |", "|---|---|---|---|---|"]
    for r in sorted(by.get("E1-5b", []), key=lambda r: r["spec"]["misalign_deg"]):
        lines.append(f"| {r['spec']['misalign_deg']:+.0f} | {r.get('U_misalignment_deg', float('nan')):+.2f} | "
                     f"{r.get('R_rotation_deg', float('nan')):+.2f} | {r.get('outcome', r.get('aborted'))} | {r['pass']} |")
    lines += ["", "## E1-6 negative controls", "", "| trial | pass | failed criteria |", "|---|---|---|"]
    for r in by.get("E1-6", []):
        bad = [k for k, v in r.items() if k.startswith("ok_") and v is False]
        lines.append(f"| {r['trial_id']} | {r['pass']} | {', '.join(bad) or r.get('aborted', '')} |")
    lines += ["", "## Failed trials (all criteria listed)", ""]
    for exp, rs in sorted(by.items()):
        for r in rs:
            if r["pass"]:
                continue
            bad = [k for k, v in r.items() if k.startswith("ok_") and v is False]
            for m in r.get("per_move", []):
                bad += [f"{m['move']}:{k}" for k, v in m.items() if k.startswith("ok_") and k != "ok_all" and not v]
            lines.append(f"* {exp}/{r['trial_id']}: {', '.join(bad) or r.get('aborted') or 'see record'}"
                         f"{' — numerical failure' if r.get('numerical_failures') else ''}"
                         f" | switches {r.get('switch_counts')}")
    settings = defaultdict(dict)
    for r in by.get("E1-7", []):
        tag, sname = r["trial_id"].split("__")
        settings[tag][sname] = "pass" if r["pass"] else "FAIL"
    lines += ["", "## E1-7 sensitivity (outcome per setting; flips are fragilities)", "", "| setting | 6-move | sexy6 |",
              "|---|---|---|"]
    for tag in sorted(settings):
        lines.append(f"| {tag} | {settings[tag].get('6move', '-')} | {settings[tag].get('sexy6', '-')} |")
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
