"""Regenerate results/SUMMARY.md from every JSON record in results/ (no filtering)."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent / "results"


def _f(v, nd=2):
    return f"{v:.{nd}f}" if isinstance(v, (int, float)) and not isinstance(v, bool) else str(v)


def main() -> None:
    rows = ["| tag | overrides vs defaults-at-run-time | sequence | moves ok | all match | max abs turn err (deg) "
            "| max opp-layer drift (deg) | max turner torque (N m) | max penetration (mm) | numerical failures |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for f in sorted(HERE.glob("c*.json")):
        r = json.loads(f.read_text())
        pm = [m for m in r["per_move"] if "move" in m]
        n = len(r["sequence"].split())
        seq = r["sequence"] if n <= 8 else f"{n}-move sequence"
        rows.append(
            f"| {r['tag']} | {', '.join(f'{k}={v}' for k, v in r['overrides'].items()) or '-'} | {seq} "
            f"| {r['moves_completed']}/{n} | {r['all_match']} "
            f"| {_f(max((abs(m['turn_error_deg']) for m in pm), default=float('nan')))} "
            f"| {_f(max((m['opposite_layer_rotation_deg_max'] for m in pm), default=float('nan')))} "
            f"| {_f(max((m['max_turner_torque_Nm'] for m in pm), default=float('nan')))} "
            f"| {_f(max((m['max_penetration_mm'] for m in pm), default=float('nan')))} "
            f"| {len(r.get('numerical_failures', [])) if 'numerical_failures' in r else 'not monitored'} |"
        )
    neg = ["| file | case | overrides | key readings | numerical failure |", "|---|---|---|---|---|"]
    keys = ("U_layer_rotation_deg", "R_layer_rotation_deg", "U_misalignment_deg", "U_change_during_R_deg",
            "observed_valid", "observed_valid_after_R_attempt", "oracle_match_after_R_attempt",
            "recovered_solved", "solved", "max_radial_deviation_mm", "max_penetration_mm",
            "max_penetration_mm_R_attempt")
    for f in sorted(HERE.glob("neg_*.json")):
        r = json.loads(f.read_text())
        kv = "; ".join(f"{k}={_f(r[k])}" for k in keys if k in r)
        neg.append(f"| {f.name} | {r['case']} | {r['overrides'] or '-'} | {kv} | {r.get('numerical_failure', '-')} |")
    (HERE / "SUMMARY.md").write_text(
        "# E1-0 results summary (auto-generated by summarize.py; UNSCORED calibration)\n\n"
        "## Turn sequences\n\n" + "\n".join(rows) + "\n\n## Negative-control pilots\n\n" + "\n".join(neg) + "\n"
    )
    print((HERE / "SUMMARY.md").read_text())


if __name__ == "__main__":
    main()
