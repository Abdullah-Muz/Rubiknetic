"""Aggregate scored G1 records into results/RESULTS.md using the frozen pass logic
(Option A: every criterion in 100 % of scored trials of E1-1...E1-6).
Every record is included; nothing is filtered."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).parent / "results"
EXPECTED = {"E1-1": 20, "E1-2": 24, "E1-3": 22, "E1-4": 40, "E1-5": 42, "E1-6": 20}


def _mx(recs, key, sub=None):
    vals = []
    for r in recs:
        if sub:
            vals += [abs(m[key]) for m in r.get(sub, []) if m.get(key) is not None]
        elif r.get(key) is not None:
            vals.append(abs(r[key]))
    return max(vals) if vals else None


def main() -> None:
    by = defaultdict(list)
    for f in sorted(OUT.glob("E1-*/*.json")):
        r = json.loads(f.read_text())
        by[r["experiment"]].append(r)
    commits = {r["source_commit"] for rs in by.values() for r in rs}
    lines = ["# G1 scored results — M1 (auto-generated by analyze.py)", "",
             f"Source commit(s): {', '.join(sorted(commits)) or 'none'}", "",
             "| Experiment | Trials run / pre-registered | Passed | Verdict |", "|---|---|---|---|"]
    verdict_all = True
    for exp in ["E1-1", "E1-2", "E1-3", "E1-4", "E1-5", "E1-6"]:
        rs = by.get(exp, [])
        n_pass = sum(r["pass"] for r in rs)
        complete = len(rs) == EXPECTED[exp]
        ok = complete and n_pass == len(rs)
        verdict_all &= ok
        lines.append(f"| {exp} | {len(rs)} / {EXPECTED[exp]} | {n_pass} | "
                     f"{'PASS' if ok else ('INCOMPLETE' if not complete else 'FAIL')} |")
    lines += ["", f"**G1 quantitative/categorical verdict for M1 (Option A): {'PASS' if verdict_all else 'NOT PASSED'}** "
              "(E1-7 and E1-8 must also be published; G1 needs user sign-off).", ""]

    seq = by.get("E1-2", []) + by.get("E1-3", []) + by.get("E1-4", [])
    lines += ["## Worst observed values in move trials (E1-2…E1-4)", "",
              f"* turn error: {_mx(seq, 'turn_error_deg', 'per_move')} deg (limit 2)",
              f"* non-target drift: {_mx(seq, 'nontarget_drift_deg', 'per_move')} deg (limit 1)",
              f"* penetration: {_mx(seq, 'penetration_mm', 'per_move')} mm (limit 0.5)",
              f"* radial position above nominal (pop check): {_mx(seq, 'radial_above_nominal_mm_so_far', 'per_move')} mm (limit 0.3)",
              f"* radial travel from trial start (reported): {_mx(seq, 'radial_change_mm_so_far', 'per_move')} mm",
              f"* turner torque: {_mx(seq, 'max_turner_torque_Nm', 'per_move')} N m (reported)", ""]
    e1 = by.get("E1-1", [])
    lines += ["## E1-1 rest", "", f"* rest rotation max {_mx(e1, 'rest_rotation_deg')} deg; radial offset max "
              f"{_mx(e1, 'radial_offset_mm_t0')} mm; above-nominal max {_mx(e1, 'radial_above_nominal_mm')} mm; "
              f"travel max {_mx(e1, 'radial_change_mm')} mm; "
              f"penetration max {_mx(e1, 'penetration_mm')} mm", ""]
    e5 = sorted(by.get("E1-5", []), key=lambda r: r["spec"]["misalign_deg"])
    lines += ["## E1-5 forgiveness (no threshold; categorical only)", "",
              "| commanded U (deg) | measured U (deg) | R rotation (deg) | outcome | pass |", "|---|---|---|---|---|"]
    for r in e5:
        lines.append(f"| {r['spec']['misalign_deg']:+.0f} | {r.get('U_misalignment_deg', float('nan')):+.2f} | "
                     f"{r.get('R_rotation_deg', float('nan')):+.2f} | {r.get('outcome', r.get('aborted'))} | {r['pass']} |")
    lines += ["", "## E1-6 negative controls", "", "| trial | pass | key values |", "|---|---|---|"]
    for r in by.get("E1-6", []):
        keys = ["layer_rotation_deg", "layer_rotations_deg", "observed_valid", "radial_change_mm",
                "penetration_mm_reported_only", "max_twist_deg", "torque_at_twist_15deg_Nm", "final_observed_valid",
                "final_solved", "aborted"]
        kv = "; ".join(f"{k}={r[k]}" for k in keys if k in r)
        lines.append(f"| {r['trial_id']} | {r['pass']} | {kv} |")
    lines += ["", "## Failed trials (all criteria listed)", ""]
    for exp, rs in sorted(by.items()):
        for r in rs:
            if r["pass"]:
                continue
            bad = [k for k, v in r.items() if k.startswith("ok_") and v is False]
            for m in r.get("per_move", []):
                bad += [f"{m['move']}:{k}" for k, v in m.items() if k.startswith("ok_") and k != "ok_all" and not v]
            lines.append(f"* {exp}/{r['trial_id']}: {', '.join(bad) or r.get('aborted') or 'see record'}"
                         f"{' — numerical failure' if r.get('numerical_failures') else ''}")
    e7 = by.get("E1-7", [])
    lines += ["", "## E1-7 sensitivity (outcome per setting; flips are fragilities)", "",
              "| setting | 6-move | sexy6 |", "|---|---|---|"]
    settings = defaultdict(dict)
    for r in e7:
        tag, sname = r["trial_id"].split("__")
        settings[tag][sname] = "pass" if r["pass"] else "FAIL"
    for tag in sorted(settings):
        lines.append(f"| {tag} | {settings[tag].get('6move', '-')} | {settings[tag].get('sexy6', '-')} |")
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
