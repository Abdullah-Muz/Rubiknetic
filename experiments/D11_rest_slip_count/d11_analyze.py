"""D11 analysis (PROTOCOL.md definitions). Reads results/ and the M5 E1-1 records; prints a markdown report."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import beta

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
M5 = REPO / "experiments/E5_scored_m5/results/E1-1"
WIN, THR, DT = 8, 0.2, 0.025


def cp(k: int, n: int) -> tuple[float, float]:
    lo = 0.0 if k == 0 else beta.ppf(0.025, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(0.975, k + 1, n - k)
    return lo, hi


def events(rec: dict, t: np.ndarray) -> list[dict]:
    ts = rec["timeseries"]
    per_cubie: dict[str, list[tuple[int, int, float]]] = {}
    for f, rows in ts["rot_deg"].items():
        a = np.array(rows)
        if len(a) <= WIN:
            continue
        d = a[WIN:] - a[:-WIN]                      # change over 200 ms, starting at sample k
        for j, name in enumerate(rec["members"][f]):
            for k in np.nonzero(np.abs(d[:, j]) >= THR)[0]:
                per_cubie.setdefault(name, []).append((int(k), int(k) + WIN, float(abs(d[k, j]))))
    out = []
    for name, ws in per_cubie.items():
        ws.sort()
        cur = list(ws[0])
        for s, e, m in ws[1:]:
            if s <= cur[1]:
                cur[1], cur[2] = max(cur[1], e), max(cur[2], m)
            else:
                out.append((name, *cur)); cur = [s, e, m]
        out.append((name, *cur))
    return [{"cubie": n, "t_start_s": float(t[s]), "t_end_s": float(t[e]), "size_deg": m} for n, s, e, m in out]


def main() -> None:
    rows, allev, peaks_ev, peaks_no = [], [], [], []
    n10 = n60 = 0
    lines = ["# D11 report (generated by d11_analyze.py)", "",
             "| seed | M5 recorded ° | 0–10 s peak ° | repro | peak cubie | events 0–10 s | events 10–60 s | events (t s, cubie, type, size °, torque mN m, rank) | peak cubie slipped |",
             "|---|---|---|---|---|---|---|---|---|"]
    for p in sorted((HERE / "results").glob("rest60_s*.json")):
        r = json.loads(p.read_text()); rec = r["record"]; s = r["seed"]; at = r["attribution"]
        ts = rec["timeseries"]
        t = np.array(ts["t"]) - ts["t"][0] + DT
        recorded = json.loads((M5 / f"rest_s{s}.json").read_text())["rest_rotation_deg"]
        repro = abs(r["rest_rotation_deg"] - recorded) <= 1e-9
        ev = events(rec, t)
        names = rec["magnet_bodies"]; T0 = np.array(ts["mag_torque_Nm"][0])
        for e in ev:
            i = names.index(e["cubie"]) if e["cubie"] in names else None
            e["type"] = "corner" if "0" not in e["cubie"].split("_")[1] else "edge"
            e["torque_mNm"] = None if i is None else float(T0[i] * 1e3)
            e["torque_rank"] = None if i is None else int((T0 > T0[i]).sum()) + 1
            e["seed"] = s
        e10 = [e for e in ev if e["t_start_s"] <= 10.0]
        n10 += bool(e10); n60 += bool(ev); allev += ev
        slipped = at["peak_cubie"] in {e["cubie"] for e in e10}
        (peaks_ev if e10 else peaks_no).append(r["rest_rotation_deg"])
        desc = "; ".join(f"{e['t_start_s']:.2f}, {e['cubie'][6:]}, {e['type']}, {e['size_deg']:.3f}, "
                         f"{e['torque_mNm']:.1f}, {e['torque_rank']}" for e in ev) or "–"
        lines.append(f"| {s} | {recorded:.4f} | {r['rest_rotation_deg']:.4f} | {'OK' if repro else '**FAIL**'} | "
                     f"{at['peak_cubie'][6:]} | {len(e10)} | {len(ev) - len(e10)} | {desc} | {slipped} |")
    n = len(peaks_ev) + len(peaks_no)
    sizes = np.array([e["size_deg"] for e in allev]) if allev else np.array([])
    lo10, hi10 = cp(n10, n); lo60, hi60 = cp(n60, n)
    lines += ["", "## Summary",
              f"- Seeds with ≥ 1 fast slip event in 0–10 s: **{n10} / {n}** (95 % CI {lo10:.2f}–{hi10:.2f})",
              f"- Seeds with ≥ 1 fast slip event in 0–60 s: **{n60} / {n}** (95 % CI {lo60:.2f}–{hi60:.2f})",
              f"- Events: {len(allev)}; size (max 200 ms change) "
              + (f"min {sizes.min():.3f}, median {np.median(sizes):.3f}, max {sizes.max():.3f} °" if len(sizes) else "–"),
              f"- Slipping cubies by type: corner {sum(e['type'] == 'corner' for e in allev)}, edge {sum(e['type'] == 'edge' for e in allev)}",
              f"- Magnet-torque rank of slipping cubies (1 = largest of 20): {sorted(e['torque_rank'] for e in allev if e['torque_rank'])}",
              f"- 0–10 s peaks, seeds with an event in 0–10 s: {sorted(round(x, 3) for x in peaks_ev)}",
              f"- 0–10 s peaks, seeds without: {sorted(round(x, 3) for x in peaks_no)}"]
    print("\n".join(lines))
    (HERE / "events.json").write_text(json.dumps(allev, indent=1))


if __name__ == "__main__":
    main()
