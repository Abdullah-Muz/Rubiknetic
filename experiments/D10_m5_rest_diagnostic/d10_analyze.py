"""D10 analysis: applies PROTOCOL.md section 4 to results/*.json. Reads only; prints a report."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
SEEDS = (10001, 10000)
RECORDED = {10001: 0.5602934615568214, 10000: 0.4979196969239446}


def load() -> dict:
    out = {}
    for p in sorted(RES.glob("A*_s*.json")):
        r = json.loads(p.read_text())
        out[(r["arm"], r["seed"])] = r
    return out


def main() -> int:
    R = load()
    P = {k: v["rest_rotation_deg"] for k, v in R.items()}
    lines = ["# D10 report (generated by d10_analyze.py)", ""]

    # reproduction gate
    gate = []
    for s in SEEDS:
        a0, a0i = P.get(("A0", s)), P.get(("A0i", s))
        ok0 = a0 is not None and abs(a0 - RECORDED[s]) <= 1e-6
        oki = a0 is not None and a0i is not None and abs(a0i - a0) <= 1e-9
        gate.append(ok0 and oki)
        lines.append(f"- Reproduction s{s}: recorded {RECORDED[s]:.10f}, A0 {a0!r}, A0i {a0i!r} -> "
                     f"A0 {'OK' if ok0 else 'FAIL'}, A0i {'OK' if oki else 'FAIL'}")
    if not all(gate):
        lines.append("\n**Reproduction gate FAILED: D10 stops here (PROTOCOL 4).**")
        print("\n".join(lines))
        return 1

    lines += ["", "| arm | seed | peak ° | ratio to A0 | face | cubie | t (s) | layer mean ° | label | solver max iter | limit hits | aborted |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ("A0", "A0i", "A1", "A2", "A3", "A4", "A5"):
        for s in SEEDS:
            r = R.get((arm, s))
            if r is None:
                lines.append(f"| {arm} | {s} | missing |")
                continue
            at = r.get("attribution", {})
            ts = r.get("record", {}).get("timeseries", {})
            mi = max(ts.get("solver_max_iter", [0]) or [0])
            hits = sum(ts.get("solver_limit_hits", [0]) or [0])
            ab = r.get("record", r.get("frozen_record", {})).get("aborted", "")
            lines.append(f"| {arm} | {s} | {P[(arm, s)]:.4f} | {P[(arm, s)] / P[('A0', s)]:.3f} | "
                         f"{at.get('peak_face', '')} | {at.get('peak_cubie', '')} | {at.get('peak_time_s', float('nan')):.3f} | "
                         f"{at.get('layer_mean_deg_at_peak', float('nan')):.4f} | {at.get('label', '')} | {mi} | {hits} | {ab} |")

    a0 = {s: P[("A0", s)] for s in SEEDS}
    r1 = all(P[("A2", s)] <= 0.5 * a0[s] and min(P[("A2", s)], a0[s]) <= P[("A1", s)] <= max(P[("A2", s)], a0[s])
             for s in SEEDS)
    within = all(abs(P[(a, s)] - a0[s]) <= 0.2 * a0[s] for a in ("A1", "A2") for s in SEEDS)
    a4 = all(P[("A4", s)] <= 0.5 * a0[s] for s in SEEDS)
    r2 = within or a4
    creep = {s: R[("A5", s)]["attribution"].get("creep_excess_deg") for s in SEEDS}
    r3 = any(c is not None and c >= 0.05 for c in creep.values())
    seeds_agree = {}
    for s in SEEDS:
        seeds_agree[s] = (P[("A2", s)] <= 0.5 * a0[s], abs(P[("A2", s)] - a0[s]) <= 0.2 * a0[s], P[("A4", s)] <= 0.5 * a0[s])

    lines += ["", "## Decision rule (PROTOCOL 4)",
              f"- Rule 1 (mostly numerical): {r1}",
              f"- Rule 2 (model behaviour): {r2}  [A1 and A2 within ±20 %: {within}; A4 ≤ 0.5 × A0: {a4}]",
              f"- Rule 3 (creep, A5 50–60 s exceeds 0–10 s peak by ≥ 0.05°): {r3}  "
              f"[excess: {', '.join(f's{s} {c:+.4f}°' for s, c in creep.items())}]",
              f"- Per-seed (A2 ≤ 0.5×A0, A2 within ±20 %, A4 ≤ 0.5×A0): {seeds_agree}"]
    if r3:
        outcome = "CREEP (rule 3): engineering review"
    elif r1 and not r2:
        outcome = "MOSTLY NUMERICAL (rule 1): M6 pre-registration with the finer setting and new seeds, disclosed"
    elif r2 and not r1:
        outcome = ("MODEL BEHAVIOUR (rule 2): engineering review" +
                   (" of the magnet model (A4 removes it)" if a4 else " of the mechanism"))
    else:
        outcome = "INCONCLUSIVE (rule 4): reported; the user decides"
    lines += ["", f"**Outcome: {outcome}**"]
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
